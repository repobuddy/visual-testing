/**
 * The sub-groups every package section shares. Stage 1 of the website reorganization
 * (docs/proposals/website-organization.md) defines them once so `addon` and `plugin` cannot drift apart.
 * Each entry names a folder under `src/content/docs/<package>/`.
 *
 * The list is empty until the pages move into those folders (stage 2). Then it becomes, in order:
 * `{ label: 'Guides', directory: 'guides' }`, `{ label: 'Configuration', directory: 'configuration' }`,
 * `{ label: 'API reference', directory: 'reference' }`.
 *
 * @type {ReadonlyArray<{ label: string, directory: string }>}
 */
export const PACKAGE_SUB_GROUPS = []

/**
 * Build the sidebar group of one package section from the shared sub-group definition.
 * Pages directly under the package folder stay autogenerated.
 *
 * @param {{ label: string, directory: string }} section
 * @param {ReadonlyArray<{ label: string, directory: string }>} [subGroups]
 */
export function packageGroup({ label, directory }, subGroups = PACKAGE_SUB_GROUPS) {
	return {
		label,
		items: [
			{ autogenerate: { directory } },
			...subGroups.map((sub) => ({
				label: sub.label,
				autogenerate: { directory: `${directory}/${sub.directory}` },
			})),
		],
	}
}
